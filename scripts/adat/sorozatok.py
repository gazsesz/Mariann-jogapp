def build():
    items = []
    for (i, sk, hu, en, cat, lv, trad, sided, dur, reps, flow, ben, cau, pc, sc, bn) in S:
        for (pose, br, _) in flow:
            assert pose in POSES, (i, pose)
            assert br in BREATH, (i, br)
        low = [c for c in [pc] + sc if c <= 5]
        prim = CH2EL[low[0]] if low else 'eter'
        sec = []
        for c in low:
            e = CH2EL[c]
            if e != prim and e not in sec:
                sec.append(e)
        steps = [
            f"{POSES[p]['hu']} – {BREATH[br]}" + (f": {cue}" if cue else "")
            for (p, br, cue) in flow
        ]
        items.append({
            "id": i, "sanskrit": sk, "hu": hu, "en": en, "category": cat, "level": lv, "traditions": trad,
            "sided": sided, "rounds": reps, "duration": dur,
            "flow": [{"pose": p, "breath": br, **({"cue": cue} if cue else {})} for (p, br, cue) in flow],
            "steps": steps, "benefits": ben, "cautions": cau,
            "chakras": {"primary": pc, "secondary": sc},
            "elements": {"primary": prim, "secondary": sec}, "benefitAreas": bn,
        })
    ids = [x["id"] for x in items]
    assert len(ids) == len(set(ids))
    return {"version": 1, "kind": "sequence", "categories": CATS, "items": items}


